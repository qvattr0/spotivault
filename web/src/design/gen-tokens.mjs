#!/usr/bin/env node
// Generates tokens.css from tokens.json.
//
// tokens.json is the output of Print(GetVariables()) on docs/ui-design/spotivault.pen,
// read through the Pen MCP. Re-export it from there; don't edit it by hand.
//
// Plain Node 22, no dependencies. Run from anywhere:
//   node web/src/design/gen-tokens.mjs           writes tokens.css
//   node web/src/design/gen-tokens.mjs --check   exits 1 if tokens.css is out of date
//
// Rules:
// - Each variable becomes a CSS custom property with the same name: `accent` -> `--accent`.
// - color: the hex value as is (#RRGGBBAA is valid CSS).
// - number: px, unless the name says it's unitless (weight, line height, opacity, ratio, scale).
// - string: font variables (`font`, `font-*`) get a generic fallback after the .pen family.
// - boolean: 1 or 0.
// - A value that is a reference (`$name`) becomes `var(--name)`.
// - Themed values: the default theme (the first value of each axis) goes in :root,
//   the others in [data-<axis>="<value>"] blocks. The .pen file has no themes today.

import { readFileSync, writeFileSync } from 'node:fs';

const here = new URL('./', import.meta.url);
const jsonUrl = new URL('tokens.json', here);
const cssUrl = new URL('tokens.css', here);

const { variables = {}, themes = {} } = JSON.parse(readFileSync(jsonUrl, 'utf8'));

const UNITLESS = /(weight|line-height|leading|opacity|ratio|scale|z-index)$/;

function propName(name) {
  const safe = name.replace(/[^A-Za-z0-9_-]/g, '-');
  if (safe !== name) console.warn(`gen-tokens: renamed "${name}" to "--${safe}"`);
  return `--${safe}`;
}

function fontStack(name, family) {
  const quoted = /^[A-Za-z-]+$/.test(family) ? family : `"${family}"`;
  const generic = /mono/.test(name) ? 'ui-monospace, monospace' : 'system-ui, sans-serif';
  return `${quoted}, ${generic}`;
}

function cssValue(name, type, value) {
  if (typeof value === 'string' && value.startsWith('$')) return `var(${propName(value.slice(1))})`;
  switch (type) {
    case 'color':
      return value;
    case 'number':
      return UNITLESS.test(name) ? String(value) : `${value}px`;
    case 'string':
      return /^font(-|$)/.test(name) ? fontStack(name, value) : JSON.stringify(value);
    case 'boolean':
      return value ? '1' : '0';
    default:
      throw new Error(`gen-tokens: "${name}" has unknown type "${type}"`);
  }
}

const defaultTheme = Object.fromEntries(
  Object.entries(themes).map(([axis, values]) => [axis, values[0]]),
);

function isDefault(theme = {}) {
  return Object.entries(theme).every(([axis, value]) => defaultTheme[axis] === value);
}

function selectorFor(theme) {
  return Object.entries(theme)
    .map(([axis, value]) => `[data-${axis}="${value}"]`)
    .join('');
}

const root = [];
const themed = new Map(); // selector -> lines

for (const [name, { type, value }] of Object.entries(variables)) {
  const prop = propName(name);
  if (!Array.isArray(value)) {
    root.push(`  ${prop}: ${cssValue(name, type, value)};`);
    continue;
  }
  const fallback = value.find((v) => !v.theme) ?? value.find((v) => isDefault(v.theme)) ?? value[0];
  root.push(`  ${prop}: ${cssValue(name, type, fallback.value)};`);
  for (const entry of value) {
    if (!entry.theme || entry === fallback) continue;
    const selector = selectorFor(entry.theme);
    if (!themed.has(selector)) themed.set(selector, []);
    themed.get(selector).push(`  ${prop}: ${cssValue(name, type, entry.value)};`);
  }
}

const blocks = [`:root {\n${root.join('\n')}\n}`];
for (const [selector, lines] of themed) blocks.push(`${selector} {\n${lines.join('\n')}\n}`);

const css = `/* Generated by gen-tokens.mjs from tokens.json (the variables of docs/ui-design/spotivault.pen).
   Don't edit: change the .pen variables, re-export tokens.json, then run
   node web/src/design/gen-tokens.mjs */

${blocks.join('\n\n')}
`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(cssUrl, 'utf8');
  } catch {}
  if (current !== css) {
    console.error('gen-tokens: tokens.css is out of date. Run node web/src/design/gen-tokens.mjs');
    process.exit(1);
  }
  console.log('gen-tokens: tokens.css is up to date.');
} else {
  writeFileSync(cssUrl, css);
  console.log(`gen-tokens: wrote ${Object.keys(variables).length} tokens to tokens.css`);
}
