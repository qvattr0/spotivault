// Vite: the dev server, the production build (dist/, which the controller serves) and the preview.
//
// Where /api and /vnc go in dev and preview:
// - By default, to the mock backend (mock/server.ts). Vite starts it itself on MOCK_PORT (8081).
// - With SPOTIVAULT_BACKEND=http://localhost:8080, to a real controller instead, and no mock starts.
// - With SPOTIVAULT_VNC=http://localhost:8080 as well, only /vnc goes there: the mock API plus a real
//   container's noVNC bridge (the S2 image has one).

import { fileURLToPath } from 'node:url';
import react from '@vitejs/plugin-react';
import { defineConfig, type Plugin } from 'vite';
import { startMockServer, type MockServer } from './mock/server.ts';

const mockPort = Number(process.env.MOCK_PORT ?? 8081);
const backend = process.env.SPOTIVAULT_BACKEND || `http://localhost:${mockPort}`;
const vncBackend = process.env.SPOTIVAULT_VNC || backend;
const useMock = !process.env.SPOTIVAULT_BACKEND;

const proxy = {
  '/api': { target: backend, ws: true, changeOrigin: true },
  '/vnc': { target: vncBackend, ws: true, changeOrigin: true },
  // The mock's own controls (scenarios). Harmless against a real controller: it answers 404.
  '/__mock': { target: backend, changeOrigin: true },
};

/**
 * Starts the mock backend with the dev or preview server. One per process: when Vite restarts
 * (after a config edit) it keeps the running mock instead of starting a second one on the same port.
 */
function mockBackend(): Plugin {
  const key = Symbol.for('spotivault.mockBackend');
  const holder = globalThis as { [key]?: Promise<MockServer> };
  async function start() {
    if (!useMock) return;
    holder[key] ??= startMockServer({ port: mockPort, scenario: process.env.MOCK_SCENARIO, background: true });
    await holder[key];
  }
  return {
    name: 'spotivault-mock-backend',
    configureServer: start,
    configurePreviewServer: start,
  };
}

const repoRoot = fileURLToPath(new URL('..', import.meta.url));

export default defineConfig({
  plugins: [react(), mockBackend()],
  resolve: {
    alias: {
      '@/': fileURLToPath(new URL('./src/', import.meta.url)),
      '@mock/': fileURLToPath(new URL('./mock/', import.meta.url)),
      // The logo files, generated by docs/brand/make_logo.py. Import them, never copy them.
      '@brand/': fileURLToPath(new URL('../docs/brand/', import.meta.url)),
    },
  },
  server: {
    port: 5173,
    proxy,
    // The logo files are in ../docs/brand.
    fs: { allow: [repoRoot] },
  },
  preview: {
    port: 4173,
    proxy,
  },
  build: {
    outDir: 'dist',
    // noVNC uses top-level await.
    target: 'es2022',
  },
});
